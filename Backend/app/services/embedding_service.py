
import json
import math
import sys
from pathlib import Path
from typing import Any

import ollama

from app.config import (
    EMBEDDING_MODEL,
    OLLAMA_URL,
    PROCESSED_DATA_DIR,
    VECTOR_SIZE,
)

# --------------------------------------------------
# 1. Configuration
# --------------------------------------------------

MODEL_NAME = EMBEDDING_MODEL
OLLAMA_CLIENT = ollama.Client(host=OLLAMA_URL, timeout=120)

# Nomic model input limit is 512 tokens.
# Keep a safety margin because our tokenizer is approximate.
SAFE_TOKEN_LIMIT = 480

BACKEND_DIR = Path(__file__).resolve().parents[2]
PROCESSED_DIR = PROCESSED_DATA_DIR

# Metadata fields that should survive embedding and indexing.
METADATA_FIELDS = (
    "section_heading",
    "domain",
    "key_concepts",
    "summary",
)


# --------------------------------------------------
# 2. Load chunks generated by text_chunker.py
# --------------------------------------------------

def load_chunks(document_id: str) -> tuple[dict, list]:
    """Load the processed chunk JSON for one document."""

    if not isinstance(document_id, str) or not document_id.strip():
        raise ValueError("Document ID cannot be empty.")

    if (
        Path(document_id).name != document_id
        or document_id in {".", ".."}
        or "/" in document_id
        or "\\" in document_id
    ):
        raise ValueError("Invalid document_id.")

    input_path = PROCESSED_DIR / f"{document_id}_chunks.json"

    if not input_path.is_file():
        raise FileNotFoundError(
            f"Chunked JSON not found: {input_path}"
        )

    with input_path.open("r", encoding="utf-8") as file:
        data = json.load(file)

    if not isinstance(data, dict):
        raise ValueError(
            "The chunked JSON must contain a JSON object."
        )

    if data.get("document_id") != document_id:
        raise ValueError(
            "The document ID in the chunk file does not match "
            "the requested document."
        )

    chunks = data.get("chunks")

    if not isinstance(chunks, list) or not chunks:
        raise ValueError(
            "No chunks found. Expected a non-empty 'chunks' list."
        )

    return data, chunks


# --------------------------------------------------
# 3. Generate embeddings
# --------------------------------------------------

def generate_embeddings(
    document_id: str,
    save_output: bool = True,
) -> dict[str, Any]:
    """
    Generate embeddings for all chunks of a document.

    Preserves:
        document_id, chunk_id, page_number, text, token_count,
        section_heading, domain, key_concepts, and summary.

    Semantic metadata is preserved when available. This function
    does not invent or generate missing semantic metadata.
    """

    source_data, chunks = load_chunks(document_id)

    embedded_chunks = []
    embedding_dimension = None

    for index, chunk in enumerate(chunks, start=1):

        # Validate chunk structure.
        if not isinstance(chunk, dict):
            raise ValueError(
                f"Chunk {index} must be a JSON object."
            )

        text = chunk.get("text")

        if not isinstance(text, str) or not text.strip():
            raise ValueError(
                f"Chunk {index} has missing or empty text."
            )

        chunk_id = chunk.get(
            "chunk_id",
            f"chunk_{index:05d}",
        )

        chunk_document_id = (
            chunk.get("document_id") or document_id
        )

        if chunk_document_id != document_id:
            raise ValueError(
                f"Chunk {chunk_id} belongs to a different document."
            )

        token_count = chunk.get("token_count")

        # Reject chunks exceeding the estimated safe limit.
        if token_count is not None:
            if (
                not isinstance(token_count, int)
                or isinstance(token_count, bool)
                or token_count < 0
            ):
                raise ValueError(
                    f"Invalid token_count for chunk {chunk_id}."
                )

            if token_count > SAFE_TOKEN_LIMIT:
                raise ValueError(
                    f"Chunk {chunk_id} has {token_count} estimated "
                    f"tokens. The safety limit is {SAFE_TOKEN_LIMIT}. "
                    "Reduce CHUNK_SIZE in text_chunker.py and "
                    "regenerate the chunks."
                )

        # Nomic document embedding prefix.
        embedding_input = f"search_document: {text.strip()}"

        # Request an embedding from Ollama.
        try:
            response = OLLAMA_CLIENT.embed(
                model=MODEL_NAME,
                input=embedding_input,
            )

        except Exception as exc:
            raise RuntimeError(
                f"Embedding failed for chunk {chunk_id}. "
                f"Check Ollama and confirm that model "
                f"'{MODEL_NAME}' is installed."
            ) from exc

        vectors = response.embeddings

        if not vectors or not vectors[0]:
            raise ValueError(
                f"Model returned an empty vector for {chunk_id}."
            )

        vector = vectors[0]

        if len(vector) != VECTOR_SIZE:
            raise ValueError(
                f"Expected {VECTOR_SIZE} embedding dimensions for "
                f"chunk {chunk_id}, but Ollama returned {len(vector)}."
            )

        # Validate numerical values.
        if not all(
            isinstance(value, (int, float))
            and not isinstance(value, bool)
            and math.isfinite(value)
            for value in vector
        ):
            raise ValueError(
                f"Invalid numerical values in {chunk_id}."
            )

        # Ensure that all chunks use the same vector dimension.
        if embedding_dimension is None:
            embedding_dimension = len(vector)

        elif len(vector) != embedding_dimension:
            raise ValueError(
                "Inconsistent embedding dimensions detected."
            )

        # Preserve the existing fields.
        embedded_chunk = {
            "document_id": chunk_document_id,
            "chunk_id": chunk_id,
            "page_number": chunk.get("page_number"),
            "text": text.strip(),
            "token_count": token_count,
            "embedding": vector,
        }

        # Preserve optional metadata added by the chunking pipeline.
        for field in METADATA_FIELDS:
            value = chunk.get(field)

            if value is not None:
                embedded_chunk[field] = value

        embedded_chunks.append(embedded_chunk)

        print(
            f"Embedded chunk {index}/{len(chunks)} "
            f"({chunk_id})"
        )

    # Prepare the complete embedding result.
    result = {
        "document_id": document_id,
        "source_file": source_data.get("source_file"),
        "model": MODEL_NAME,
        "embedding_dimension": embedding_dimension,
        "chunk_count": len(embedded_chunks),
        "chunks": embedded_chunks,
    }

    # Save the result for debugging and vector indexing.
    if save_output:
        PROCESSED_DIR.mkdir(
            parents=True,
            exist_ok=True,
        )

        output_path = (
            PROCESSED_DIR
            / f"{document_id}_embeddings.json"
        )

        temporary_path = (
            PROCESSED_DIR
            / f".{document_id}_embeddings.json.tmp"
        )

        try:
            with temporary_path.open(
                "w",
                encoding="utf-8",
            ) as file:
                json.dump(
                    result,
                    file,
                    ensure_ascii=False,
                    indent=2,
                )

            temporary_path.replace(output_path)

        finally:
            if temporary_path.exists():
                temporary_path.unlink()

        print(f"\nEmbeddings saved to: {output_path}")

    print("\nEmbedding generation completed.")
    print(f"Document ID: {document_id}")
    print(f"Chunks embedded: {len(embedded_chunks)}")
    print(f"Vector dimensions: {embedding_dimension}")

    return result


# --------------------------------------------------
# 4. Execute from the terminal
# --------------------------------------------------

if __name__ == "__main__":

    if len(sys.argv) != 2:
        print(
            "Usage: python -m app.services.embedding_service "
            "<document_id>"
        )
        sys.exit(1)

    document_id = sys.argv[1]

    try:
        generate_embeddings(document_id)

    except Exception as exc:
        print(f"\nERROR: {exc}")
        sys.exit(1)
